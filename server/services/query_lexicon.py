def fuzzy_lookup_latin(token: str) -> Optional[Tuple[str, ...]]:
    """Sửa lỗi chính tả tự động cho tên riêng tiếng Anh/Latin (vd: 'havard' -> 'harvard' -> '哈佛')."""
    t = (token or "").strip().lower()
    if len(t) < 5 or " " in t or not (t.isascii() and t.isalpha()):
        return None
    matches = difflib.get_close_matches(t, _LATIN_PROPER_KEYS, n=1, cutoff=0.80)
    if matches:
        return _FOLDED_MAP.get(matches[0])
    return None
