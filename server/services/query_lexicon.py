# Danh sách khoá đơn Latin (>= 5 ký tự, không dấu) để tự động bắt lỗi gõ phím (havard, berkley, princton...)
_LATIN_PROPER_KEYS = tuple(
    k for k in _FOLDED_MAP if " " not in k and len(k) >= 5 and k.isascii() and k.isalpha()
)

